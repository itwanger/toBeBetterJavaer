def _compile(rules: tuple[tuple[str, str], ...]) -> tuple[tuple[re.Pattern[str], str], ...]:
    return tuple((re.compile(pattern), suggestion) for pattern, suggestion in rules)


COMPILED_FAIL = _compile(FAIL_RULES)
COMPILED_WARN = _compile(WARN_RULES)


def find_hits(prose: str, compiled: tuple[tuple[re.Pattern[str], str], ...]):
    """返回 (起始位置, 命中文本, 建议写法)，按位置排序，同一位置只报一次。"""
    hits = {}
    for pattern, suggestion in compiled:
        for match in pattern.finditer(prose):
            hits.setdefault(match.start(), (match.start(), match.group(), suggestion))
    return [hits[key] for key in sorted(hits)]
